# ===========================================================================
# 为什么只剩这些层（Issue #278）
# ---------------------------------------------------------------------------
# 用户 2026-09-25：「所有测试文件，除了功能验证的测试之外，删除尽可能多的
# 其他测试，特别是界面相关的测试，我的目的是构建时间变短。」
#
# 原先这一圈分四十几层，其中**一大半是界面测试**：jsdom 起真页面、挂脚本、
# 敲搜索框、量矩形、扫样式、扫源码里有没有某句话，外加一层真浏览器（puppeteer
# 起 Chrome 跑 PWA）。它们的共同点：
#   · 慢 —— 起一次 jsdom 就是几百毫秒，几十层叠起来是分钟级；
#     那一层 puppeteer 光装 Chrome 就要几分钟；
#   · 脆 —— 页面结构一改（删一个 class、换一句文案、挪一处入口）就红，
#     而红的往往不是功能，是「界面长得跟上次不一样了」；
#   · 与「功能对不对」无关 —— 用户要守的是背诵、登录、同步、判重这些**能不能用**。
#
# 所以这一轮把界面相关的整层删掉，保留的都是**功能验证**：数据、算法、
# 接口、存储、同步、判重、注音内核。运行在 10 秒上下（原先 30 秒起步，
# puppeteer 那一层还要多几分钟装浏览器）。
#
# 删掉的东西去哪了：需要看的界面回归，靠人点一遍（`npm start` 起本地服务），
# 以及 CI 之外的真机验收 —— 不再由构建时间替我们盯。
# ===========================================================================
#
# ⚠️ 从这一轮起**不再需要 jsdom**（也就没有「临时装一份」那一段了）：
