/* ==========================================================================
   昭明文选 · 出处精细化（Issue #512）
   --------------------------------------------------------------------------
   480 条的 `source` 与 `selection` 原先**都是「《文选》」** —— 两枚标签一模一样，
   等于出处那一行什么都没记。精校本的类目明明就在 `gradeGroup` 里躺着
   （赋 · 京都上 / 诗 · 补亡 / 骚 / 七 / 诏 / 表……），却没上到出处那一行。

   按与《古文观止》相同的口径改为两重出处：

     source     这首诗 / 这篇赋**所出之书** —— 作者本人的别集（《曹子建集》
                《陆士衡集》），集部失传或本无语集者退到总集（《楚辞》
                《史记》《汉书》）；
     selection  收它的**选本** —— 一律《文选》（与《古文观止》那 231 条一致）。

   详情页两枚标签并列（`source` 实心在前、`selection` 浅色在后），
   于是《西京赋》读到的是「东汉 · 张平子 · 《张平子集》 · 《文选》」。

   几处需要交代的口径：
     · 建安七子 / 三曹 / 两晋诸家的诗文集**多数原本无集或早已散佚**，通行
       著录的都是后人辑本（《蔡中郎集》《孔北海集》……）。这一类仍按
       **通行辑本名**记 —— 与《唐诗》那边用《杜工部集》同理：读的人认的是
       这部书，不是它的版本源流。
     · 无主名的两篇（`古辞·乐府三首`、`佚名·古诗十九首`）出处在书本身，
       记《乐府诗集》《玉台新咏》，不记「无名氏集」（没有这样的书）。
     · 帝王语书（汉武帝《诏》、汉高祖《诏》）集子失传，退到《汉书》。
     · 屈原 / 宋玉辞赋与《招隐士》在《文选》「骚」类，通行著录即《楚辞》。

   ⚠️ 这是脚本、不是数据 —— 表在下面，改完重跑即可（幂等）。
      用法：node scripts/fix-zhaoming-source.js
   ========================================================================== */
