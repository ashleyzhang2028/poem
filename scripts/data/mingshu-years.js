/* 「国别 / 时代」栏 → 粗档（书目表里没给年份时的兜底）。
   只保证大类先后对，不追求精确。 */
function eraFallback(era) {
  const t = String(era || '');
  if (/先秦|春秋|战国|西周|商/.test(t)) return -600;
  if (/秦|汉|三国|晋|南北朝/.test(t)) return 200;
  if (/隋|唐|五代/.test(t)) return 700;
  if (/宋|辽|金/.test(t)) return 1000;
  if (/元/.test(t)) return 1300;
  if (/明/.test(t)) return 1500;
  if (/清/.test(t)) return 1700;
  if (/近代|清末|民国|近现代/.test(t)) return 1920;
  if (/当代|现代/.test(t)) return 1980;
  if (/古希腊|古罗马|两河|古埃及|古印度/.test(t)) return -500;
  if (/中世纪|文艺复兴|启蒙/.test(t)) return 1500;
  if (/十九世纪|19 世纪/.test(t)) return 1850;
  if (/二十世纪|20 世纪/.test(t)) return 1950;
  return 1900;
}

function yearOf(title, era) {
  if (YEARS[title] != null) return YEARS[title];
  return eraFallback(era);
}

