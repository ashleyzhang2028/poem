/* 姓名 → 行 */
const BY_NAME = {};
PEOPLE.forEach(function (r) { BY_NAME[r[0]] = r; });

/* PLAN：按组摊成装机脚本认的形状 */
const PLAN = (function () {
  const groups = {};
  Object.keys(GROUP_OF_NAME).forEach(function (k) {
    const row = BY_NAME[k];
    if (!row) throw new Error('mingren-round13：' + k + ' 在 PEOPLE 里找不到对应的行');
    const g = GROUP_OF_NAME[k];
    (groups[g] = groups[g] || []).push(row);
  });
  const plan = Object.keys(groups).map(function (g) { return { group: g, rows: groups[g] }; });
  const planned = {};
  plan.forEach(function (p) { p.rows.forEach(function (r) { planned[r[0]] = true; }); });
  const orphan = PEOPLE.filter(function (r) { return !planned[r[0]]; }).map(function (r) { return r[0]; });
  if (orphan.length) throw new Error('mingren-round13：这些人没有归组：' + orphan.join('、'));
  return plan;
})();

module.exports = { PEOPLE: PEOPLE, PLAN: PLAN, GROUP_OF_NAME: GROUP_OF_NAME };
