/* ── 三、PLAN：按组摊成装机脚本认的形状 ───────────────────────────────── */
const PLAN = [];
(function () {
  const groups = {};
  Object.keys(GROUP_OF_NAME).forEach(function (k) {
    const real = ALIAS[k] || k;
    const row = BY_NAME[real];
    if (!row) throw new Error('mingren-round12：' + k + ' 在 PEOPLE 里找不到对应的行（' + real + '）');
    const g = GROUP_OF_NAME[k];
    (groups[g] = groups[g] || []).push(row);
  });
  /* 行数与名单数对不上就当场报错（防「加了人忘了归组」这类静默漏条） */
  const planned = {};
  PLAN.length = 0;
  Object.keys(groups).forEach(function (g) { PLAN.push({ group: g, rows: groups[g] }); });
  PLAN.forEach(function (p) { p.rows.forEach(function (r) { planned[r[0]] = true; }); });
  const orphan = PEOPLE.filter(function (r) { return !planned[r[0]]; }).map(function (r) { return r[0]; });
  if (orphan.length) throw new Error('mingren-round12：这些人没有归组：' + orphan.join('、'));
})();

