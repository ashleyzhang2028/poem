/* 索引：按 id 查、按卷查 */
(function () {
  window.GUWEN_ALL = window.POEMS_GUWEN;
  window.getGuwenById = function (id) {
    return window.POEMS_GUWEN.filter(function (p) { return p.id === id; })[0] || null;
  };
  window.getGuwenGroups = function () {
    var groups = [];
    window.POEMS_GUWEN.forEach(function (p) {
      var g = p.gradeGroup || "其他";
      var hit = groups.filter(function (it) { return it.name === g; })[0];
      if (!hit) { hit = { name: g, items: [] }; groups.push(hit); }
      hit.items.push(p);
    });
    return groups;
  };
  /** 已收录（有正文与译文）的篇数 */
  window.guwenDoneCount = function () {
    return window.POEMS_GUWEN.filter(function (p) { return p.text && p.translation; }).length;
  };
})();
