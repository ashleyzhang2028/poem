/* ==========================================================================
   分组顺序总表（Issue #69 收尾 · 正文收归主表）
   --------------------------------------------------------------------------
   每一部集子都有「组的先后」：唐诗按卷一至卷八、宋词按词牌、古文观止按卷次、
   昭明文选按三十九类文体、小古文按蒙学到诸子的认知顺序。
   原先这份顺序写在各自的挂载脚本里（js/tangshi.js 的 GROUP_ORDER …），
   只有「进那一页读那一部」时才用得上。

   现在多了一处要用它：**作品主表**（data/works-index.js）。
   同一篇作品可能在几部集子里各存一份正文（《登高》课内高一上 + 唐诗卷五、
   《桃花源记》课内八年级下 + 古文观止卷六……）。主表要把这几份合成一份，
   就得回答「合并之后这一篇排在谁的后面」—— 那要看这一篇**主条目**
   （课内优先，没有课内条目时取选本里的第一条）所在组的顺序。
   顺序若只在页面的挂载脚本里，主表就读不到；把页面的那份搬过来，
   又会出现两份顺序各改各的。所以统一在这里给出，页面与主表都引它。

   ⚠️ 这里是**顺序的唯一来源**：增删卷次 / 文体 / 词牌分组时改这一份，
      页面（js/tangshi.js 等）与主表跟着变，不会两边对不上。

   ## 为什么主表这一层要合并组头

   《静夜思》在课内属「一年级下册」、在唐诗三百首属「卷七 五言绝句」：
   正文同一篇、组名却是两个。合并成一篇之后，列表里这一篇只能显示一个组名
   （否则同一篇要出现两次），取的是课内那个 —— 教材口径优先。
   唐诗页因此会看到《静夜思》落在「一年级下册」这一组里，
   而不是它本来所在的「卷七 五言绝句」（那一组少一条）。
   这是「正文收归主表、课内优先」的必然结果，也是用户要的口径：
   学生背的是课本上那一篇，进唐诗页再看到它时，也该在课内那一档里找到。
   ========================================================================== */
(function () {
  "use strict";

  var GROUPS = {
    /* 小古文：按认知顺序，见 js/classic.js */
    classic: [
      "蒙学经典", "寓言故事", "神话传说", "人物故事",
      "志人逸事", "治学勤读", "山水游记", "诸子论道"
    ],

    /* 唐诗三百首：按选本篇次，卷一至卷八 */
    tangshi: [
      "卷一 五言古诗", "卷二 七言古诗", "卷三 五言乐府", "卷四 七言乐府",
      "卷五 五言律诗", "卷六 七言律诗", "卷七 五言绝句", "卷八 七言绝句"
    ],

    /* 宋词三百首：按词牌（顺序由 js/songci.js 给出，按选本目录首次出现的次第） */
    songci: window.SONGCI_GROUP_ORDER || null,

    /* 古文观止：十二卷 */
    guwen: [
      "卷一 周文", "卷二 周文", "卷三 周文", "卷四 秦文",
      "卷五 汉文", "卷六 汉文", "卷七 六朝唐文", "卷八 唐文",
      "卷九 唐宋文", "卷十 宋文", "卷十一 宋文", "卷十二 明文"
    ],

    /* 昭明文选：三十九类文体，按原书次第 */
    zhaoming: window.ZHAOMING_GROUP_ORDER || null
  };

  window.GROUP_ORDER = GROUPS;

  /** 取某一部的组顺序；没有登记（或那份数据没加载）时返回空数组 —— 空数组表示
      「不重排」，列表按数据出场顺序排，与引擎的既有行为一致。 */
  window.groupOrderOf = function (bookId) {
    var v = GROUPS[bookId];
    return Array.isArray(v) ? v.slice() : [];
  };
})();
