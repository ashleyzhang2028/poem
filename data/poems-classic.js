(function () {
  window.CLASSIC_ALL = window.POEMS_CLASSIC;
  window.getClassicById = function (id) {
    return window.POEMS_CLASSIC.filter(function (p) { return p.id === id; })[0] || null;
  };
  window.getClassicGroups = function () {
    const groups = [];
    window.POEMS_CLASSIC.forEach(function (p) {
      const g = p.gradeGroup || "其他";
      let hit = groups.filter(function (it) { return it.name === g; })[0];
      if (!hit) { hit = { name: g, items: [] }; groups.push(hit); }
      hit.items.push(p);
    });
    return groups;
  };
})();
